class PromptTemplate:
    """
    A simple class to represent and format prompt templates for LLMs.
    """
    def __init__(self, template: str):
        """
        Initializes the PromptTemplate with a template string.

        Args:
            template (str): The template string with placeholders (e.g., "Hello, {name}!").
        """
        self.template = template

    def format(self, **kwargs) -> str:
        """
        Formats the template string with provided keyword arguments.

        Args:
            **kwargs: Keyword arguments to fill the placeholders in the template.

        Returns:
            str: The formatted prompt string.
        """
        try:
            return self.template.format(**kwargs)
        except KeyError as e:
            raise ValueError(f"Missing placeholder in prompt template: {e}")

